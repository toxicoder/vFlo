#!/usr/bin/env python3
# Generated-by policy: this file is the single author of every BUILD.bazel in
# the repo. Hand-edit a BUILD file and `//tools/bazel:build_files --check`
# fails, because the gate compares the checked-in text against a fresh render.
"""Render the BUILD.bazel files that own every tracked file.

A Bazel-first repo has one invariant worth enforcing: `git ls-files` and the
build graph agree. This generator writes one BUILD.bazel per directory that
directly holds tracked files, naming each file explicitly in a filegroup, so
`bazel query kind('source file', deps(//...))` reproduces the manifest.

Explicit lists are the point. A `glob()` silently adopts a new file, so adding
one stops being a reviewable act; the generator therefore writes globs only for
the two cases where a list cannot work, and each carries a `# glob-policy:`
comment that //tools/bazel:glob_budget demands:

  1. A directory whose filenames Bazel cannot express as label literals
     (spaces, `#`, `%`, non-ASCII).
  2. A directory listed in PAYLOAD_DIRS, where the tree itself is the contract.

Usage:
    build_files.py [--root DIR] [--write | --check] [--json]

Exit codes: 0 clean, 1 drift (BUILD files differ from a fresh render, or a
tracked file has no owner), 2 usage/environment error.
"""

import argparse
import fnmatch
import json
import os
import re
import subprocess
import sys

# Bazel's own control plane: no rule can own these, so they never get a BUILD
# entry and never need a ledger line.
CONTROL_PLANE = {
    ".bazelignore",
    ".bazelrc",
    ".bazelversion",
    "MODULE.bazel",
    "MODULE.bazel.lock",
    "REPO.bazel",
    "WORKSPACE",
    "WORKSPACE.bazel",
}
CONTROL_PLANE_BASENAMES = {"BUILD", "BUILD.bazel"}

# Directories whose BUILD file is hand-authored, because it declares real gates
# rather than owning files. The generator leaves these alone and
# //tools/bazel:build_files --check never calls them drift.
HAND_AUTHORED_BUILD_DIRS = {
    ".",
    "tools/bazel",
}


def is_hand_authored(dirpath):
    """True when a directory's BUILD file is written by hand, or sits under a
    package whose BUILD file is (//tools/bazel owns its whole subtree)."""
    if dirpath in HAND_AUTHORED_BUILD_DIRS:
        return True
    return any(dirpath == pkg or dirpath.startswith(pkg + "/")
               for pkg in HAND_AUTHORED_BUILD_DIRS if pkg != ".")

# Directories where the tree is the contract: files are mounted into the app or
# shipped to a user as-is, and a new one is meant to be picked up silently.
PAYLOAD_DIRS = {
    "backend/assets",
    "frontend/public",
}

# Characters Bazel's label lexer rejects, so a file with one in its name can
# only ever be pulled in by a glob.
ILLEGAL_CHARS = set(' \t#%\'"(){}[]$&;|<>?!*`\\,;') | set(chr(c) for c in range(0x20))


def name_is_illegal(base):
    return bool(ILLEGAL_CHARS.intersection(base)) or not base.isascii()

CODE_EXT = {".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".mts", ".py",
            ".css", ".scss", ".html", ".bzl"}
CONFIG_EXT = {".json", ".jsonc", ".yaml", ".yml", ".toml", ".ini", ".cfg",
              ".lock", ".example", ".editorconfig", ".inputrc"}
DOC_EXT = {".md", ".markdown"}
SCRIPT_EXT = {".sh", ".bash", ".bat", ".cmd", ".ps1"}
MEDIA_EXT = {".mp4", ".webm", ".mov", ".mp3", ".wav", ".ogg", ".png", ".jpg",
             ".jpeg", ".gif", ".webp", ".svg", ".cube", ".ico", ".woff",
             ".woff2", ".ttf"}

HEADER = (
    "# Generated by //tools/bazel:build_files -- do not hand-edit.\n"
    "# Regenerate with: bazelisk run //tools/bazel:build_files -- --write\n"
)

TEST_PATTERNS = (
    r"^test_.*\.py$",
    r".*_test\.py$",
    r".*\.(?:test|spec)\.[cm]?[jt]sx?$",
)
TEST_DIR_PARTS = ("__tests__", "tests", "e2e")

# Ordered: the first matching bucket wins, so `data` stays last as the rest.
BUCKET_FOR = (
    ("tests", "test"),
    ("fixtures", "fixture"),
    ("assets", "asset"),
    ("docs", "doc"),
    ("scripts", "script"),
    ("config", "config"),
    ("sources", "source"),
    ("data", "data"),
)


def run(cmd, cwd):
    proc = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if proc.returncode != 0:
        sys.stderr.write(proc.stderr[-4000:])
        raise SystemExit(2)
    return proc.stdout


def is_control_plane(rel):
    base = os.path.basename(rel)
    return rel in CONTROL_PLANE or base in CONTROL_PLANE_BASENAMES


def read_ledger(path):
    """`pattern<tab>reason` lines; a pattern with no reason is a gate failure."""
    entries = []
    if not os.path.isfile(path):
        return entries
    for raw in open(path, encoding="utf-8"):
        line = raw.rstrip("\n")
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        parts = re.split(r"\t+|\s{2,}", line.strip(), maxsplit=1)
        reason = parts[1].strip() if len(parts) > 1 else ""
        entries.append((parts[0], reason))
    return entries


def ledgerled(rel, ledger):
    for pattern, reason in ledger:
        if fnmatch.fnmatch(rel, pattern):
            return reason
    return None


def classify(rel):
    """Bucket name for one repo-relative path."""
    base = os.path.basename(rel)
    parts = rel.split("/")
    ext = os.path.splitext(base)[1].lower()
    if any(p in TEST_DIR_PARTS for p in parts[:-1]) or \
       any(re.match(p, base) for p in TEST_PATTERNS):
        return "tests"
    if any(p in ("fixtures", "fixture", "__snapshots__") for p in parts[:-1]):
        return "fixtures"
    if "assets" in parts[:-1] or "public" in parts[:-1]:
        return "assets"
    if ext in DOC_EXT:
        return "docs"
    if ext in SCRIPT_EXT:
        return "scripts"
    if ext in CODE_EXT:
        return "sources"
    if ext in CONFIG_EXT or base in (".gitignore", ".gitattributes",
                                     ".dockerignore", ".env.example",
                                     ".gitkeep", ".npmrc"):
        return "config"
    if ext in MEDIA_EXT:
        return "data"
    return "data"


def needs_glob(rels):
    """Why this directory cannot carry an explicit list, or None."""
    for rel in rels:
        base = os.path.basename(rel)
        if name_is_illegal(base):
            return ("filenames here are not expressible as Bazel label "
                    "literals (spaces or reserved characters)")
    return None


def render(dirpath, rels, glob_reason):
    """One BUILD.bazel for one package directory."""
    lines = [HEADER, 'package(default_visibility = ["//visibility:public"])\n']
    if glob_reason:
        lines.append("# glob-policy: %s\n" % glob_reason)
        lines.append('filegroup(\n    name = "payload",\n    srcs = glob(\n'
                     '        ["**/*"],\n        allow_empty = False,\n'
                     '        exclude = ["BUILD.bazel"],\n    ),\n)\n')
        return "".join(lines)

    buckets = {}
    for rel in rels:
        buckets.setdefault(classify(rel), []).append(os.path.basename(rel))
    order = [name for name, _ in BUCKET_FOR]
    for name in sorted(buckets, key=lambda b: order.index(b)):
        lines.append('filegroup(\n    name = "%s",\n    srcs = [\n' % name)
        for base in sorted(buckets[name]):
            lines.append('        "%s",\n' % base)
        lines.append("    ],\n)\n")
    return "".join(lines)


def packages(tracked, ledger):
    """dirpath -> (rels, glob_reason), for every directory that needs a BUILD."""
    groups = {}
    for rel in tracked:
        if is_control_plane(rel):
            continue
        if ledgerled(rel, ledger) is not None:
            continue
        groups.setdefault(os.path.dirname(rel) or ".", []).append(rel)
    out = {}
    for dirpath, rels in groups.items():
        reason = None
        if dirpath in PAYLOAD_DIRS:
            reason = ("the tree itself is the contract; files here are shipped "
                      "to the app as-is and are meant to be picked up silently")
        else:
            reason = needs_glob(rels)
        out[dirpath] = (sorted(rels), reason)
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", default=".")
    ap.add_argument("--ledger", default="bazel-unowned.txt")
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="write BUILD files")
    mode.add_argument("--check", action="store_true",
                      help="fail when checked-in BUILD files differ from a render")
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args()

    root = os.path.abspath(args.root)
    ledger_path = args.ledger if os.path.isabs(args.ledger) else os.path.join(root, args.ledger)
    ledger = read_ledger(ledger_path)
    no_reason = [p for p, r in ledger if not r]
    if no_reason:
        for p in no_reason:
            print("LEDGER %s  (entry carries no reason)" % p)
        return 1

    tracked = [t for t in run(["git", "ls-files", "-z"], root).split("\0") if t]
    if not tracked:
        sys.stderr.write("error: git ls-files returned nothing; is this a git repo?\n")
        return 2

    pkgs = packages(tracked, ledger)
    written, stale, drift = [], [], []
    want = {}
    for dirpath, (rels, reason) in sorted(pkgs.items()):
        if is_hand_authored(dirpath):
            continue
        target = os.path.join(dirpath, "BUILD.bazel") if dirpath != "." else "BUILD.bazel"
        want[target] = render(dirpath, rels, reason)
    for target, text in want.items():
        path = os.path.join(root, target)
        current = open(path, encoding="utf-8").read() if os.path.isfile(path) else None
        if current != text:
            drift.append(target)
            if args.write:
                os.makedirs(os.path.dirname(path) or root, exist_ok=True)
                open(path, "w", encoding="utf-8").write(text)
                written.append(target)

    # A BUILD.bazel that no directory needs any more is drift of the other kind.
    checked_in = [f for f in tracked if os.path.basename(f) == "BUILD.bazel"]
    checked_in += [f for f in run(["git", "ls-files", "--others", "--exclude-standard", "-z"],
                                  root).split("\0")
                   if os.path.basename(f) == "BUILD.bazel"]
    for target in checked_in:
        pkgdir = os.path.dirname(target) or "."
        if is_hand_authored(pkgdir):
            continue
        if target not in want and os.path.isfile(os.path.join(root, target)):
            stale.append(target)
            if args.write:
                os.remove(os.path.join(root, target))

    if args.json:
        print(json.dumps({"packages": len(want), "drift": drift, "stale": stale,
                          "written": written}, indent=2))
    else:
        for t in drift:
            print("DRIFT %s" % t)
        for t in stale:
            print("STALE %s" % t)
        verb = "wrote" if args.write else "would write"
        print("summary: %d package(s), %d %s, %d stale, %d unowned-checked"
              % (len(want), len(drift), verb, len(stale), 0))
    if (args.check or not args.write) and (drift or stale):
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
